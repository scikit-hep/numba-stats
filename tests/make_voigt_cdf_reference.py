r"""
Generate voigt_cdf_reference.csv with mpmath.

Each value is computed in two independent ways, and the table is written only if
they agree to 1e-25:

- the closed form F = Re[1/2 + erf(z) / 2 + i z^2 / pi 2F2(1, 1; 3/2, 2; -z^2)] with
  z = (x - loc + i gamma) / (scale sqrt(2)), with enough extra digits to absorb its
  cancellation where gamma > |x - loc|;
- tanh-sinh quadrature of the pdf Re w(z) / (scale sqrt(2 pi)) from loc to x, added
  to 1/2, where w is the Faddeeva function.

The cdf depends only on (x - loc) / scale and gamma / scale, so the table uses
loc = 0 and scale = 1.

The run takes under a minute and can be interrupted: every value is appended to
voigt_cdf_reference.partial.csv as soon as it is computed, a rerun skips the values
already there, and the table is written (and the partial file removed) only once
every value is done.

Run with ``python make_voigt_cdf_reference.py`` (needs mpmath).
"""

import csv
from pathlib import Path

import mpmath as mp

mp.mp.dps = 40
AGREEMENT = mp.mpf("1e-25")

# Up to 30: beyond, the closed form needs thousands of digits where gamma > |x|
# (~80 s per value at gamma = 100), and gamma = 30 is already deep in the
# Cauchy regime.
GAMMAS = "0.001 0.01 0.1 0.3 1 3 10 30".split()
# Both sides of the core, around the switch to the asymptotic branch (|z| = 6,
# x near 8.49 for small gamma), and far into the Cauchy tails.
XS = "0 0.1 0.5 1 2 3 5 8 8.4 8.6 12 20 50 200 1000".split()
XS = [f"-{x}" for x in reversed(XS[1:])] + XS

OUT = Path(__file__).resolve().parent / "voigt_cdf_reference.csv"
PARTIAL = Path(__file__).resolve().parent / "voigt_cdf_reference.partial.csv"


def z_of(x: mp.mpf, gamma: mp.mpf) -> mp.mpc:
    """Return z = (x + i gamma) / sqrt(2) for loc = 0 and scale = 1."""
    return mp.mpc(x, gamma) / mp.sqrt(2)


def closed_form(x: mp.mpf, gamma: mp.mpf) -> mp.mpf:
    """Return the cdf from erf and 2F2."""
    # For gamma > |x| the two terms each grow like exp((gamma^2 - x^2) / 2) and
    # cancel; carry that many extra digits.
    extra = int(max(0, (gamma**2 - x**2) / 2) / mp.log(10)) + 20
    with mp.workdps(mp.mp.dps + extra):
        z = z_of(x, gamma)
        value = (
            mp.mpf("0.5")
            + mp.erf(z) / 2
            + 1j * z**2 / mp.pi * mp.hyp2f2(1, 1, mp.mpf("1.5"), 2, -(z**2))
        )
        return +mp.re(value)


def pdf(t: mp.mpf, gamma: mp.mpf) -> mp.mpf:
    """Return the pdf, the real part of the Faddeeva function."""
    # exp(-z^2) and erfc(-iz) are each huge or tiny far out; extra digits keep
    # their product and phase exact.
    with mp.workdps(mp.mp.dps + 20):
        z = z_of(t, gamma)
        return +(mp.re(mp.exp(-(z**2)) * mp.erfc(-1j * z)) / mp.sqrt(2 * mp.pi))


def by_quadrature(x: mp.mpf, gamma: mp.mpf) -> mp.mpf:
    """Return the cdf as 1/2 plus the integral of the pdf from 0 to x."""
    # split the integral where the pdf changes scale
    a = abs(x)
    points = (
        [mp.mpf(0)]
        + [b for b in (mp.mpf(1), 5 + gamma, 10 + 10 * gamma) if b < a]
        + [a]
    )
    integral = mp.quad(lambda t: pdf(t, gamma), points)
    return mp.mpf("0.5") + (integral if x > 0 else -integral)


def load_partial() -> dict[tuple[str, str], tuple[str, str]]:
    """Return the values of an interrupted run, (cdf, disagreement) by (gamma, x)."""
    if not PARTIAL.exists():
        return {}
    with PARTIAL.open(newline="") as f:
        return {
            (g, x): (value, difference) for g, x, value, difference in csv.reader(f)
        }


def main() -> None:
    """Compute and cross-check every value not yet computed, then write the table."""
    done = load_partial()
    todo = [(g, x) for g in GAMMAS for x in XS if (g, x) not in done]
    print(f"{len(done)} values from an earlier run, {len(todo)} to compute", flush=True)
    with PARTIAL.open("a", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        for k, (g, x) in enumerate(todo, 1):
            a = closed_form(mp.mpf(x), mp.mpf(g))
            b = by_quadrature(mp.mpf(x), mp.mpf(g))
            difference = abs(a - b)
            if difference > AGREEMENT:
                raise RuntimeError(
                    f"methods disagree at gamma={g}, x={x}: "
                    f"{mp.nstr(a, 30)} vs {mp.nstr(b, 30)}"
                )
            done[g, x] = (repr(float(a)), mp.nstr(difference, 3))
            writer.writerow([g, x, *done[g, x]])
            f.flush()
            print(f"[{k}/{len(todo)}] gamma={g} x={x}", flush=True)

    rows = [(g, x, done[g, x][0]) for g in GAMMAS for x in XS]
    worst = max(float(done[g, x][1]) for g in GAMMAS for x in XS)
    with OUT.open("w", newline="") as f:
        f.write(
            "# Voigt CDF for mu = 0, sigma = 1; "
            "generated by make_voigt_cdf_reference.py\n"
        )
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(["gamma", "x", "cdf"])
        writer.writerows(rows)
    PARTIAL.unlink()
    print(f"wrote {len(rows)} values to {OUT}")
    print(f"largest disagreement between the methods: {worst:.3g}")


if __name__ == "__main__":
    main()
